function prettyGpuType(t: string) {
  return t.replace(/_/g, " ").replace(/\bGB\b/g, "GB");
}

/** SXM4/SXM5 → SXM so live and catalog offers land on the same model row. */
function normalizeSocket(s: string) {
  const v = s.trim();
  if (/^sxm/i.test(v)) return "SXM";
  if (/^pci/i.test(v)) return "PCIe";
  return v || "PCIe";
}

function mapLiveItem(item: Record<string, unknown>, index: number): GpuOffer {
  const gpuType = String(item.gpuType || "GPU");
  const gpuCount = Math.max(1, Number(item.gpuCount || 1));
  const prices = (item.prices || {}) as { onDemand?: number };
  const vcpu = (item.vcpu || {}) as { defaultCount?: number };
  const memory = (item.memory || {}) as { defaultCount?: number };
  const provider = String(item.provider || "provider");
  const cloudId = String(item.cloudId || `${provider}-${gpuType}-${gpuCount}`);
  const socket = normalizeSocket(String(item.socket || "PCIe"));
  // Prime reports total VRAM for multi-GPU nodes (2× H100 = 160). Store per-GPU.
  const typeMem = Number(/_(\d+)GB/i.exec(gpuType)?.[1] || 0);
  const rawMem = Number(item.gpuMemory || 0);
  const perGpuMem =
    typeMem > 0 ? typeMem : gpuCount > 1 && rawMem > 0 ? Math.round(rawMem / gpuCount) : rawMem;
  return {
    id: `${provider}-${cloudId}-${gpuCount}-${index}`.replace(/\s+/g, "-").toLowerCase(),
    cloudId,
    gpuType,
    label: `${prettyGpuType(gpuType)}${socket ? ` ${socket}` : ""}`.replace(/\s+/g, " ").trim(),
    socket,
    provider,
    region: String(item.region || "unknown"),
    country: String(item.country || ""),
    dataCenter: item.dataCenter ? String(item.dataCenter) : null,
    gpuCount,
    gpuMemory: perGpuMem,
    vcpu: Number(vcpu.defaultCount || 0),
    memoryGb: Number(memory.defaultCount || 0),
    pricePerHour: Number(prices.onDemand || 0),
    stockStatus: String(item.stockStatus || "Available"),
    images: Array.isArray(item.images) ? (item.images as string[]) : ["ubuntu_22_cuda_12"],
    source: "live",
  };
}

async function fetchLiveOffers(): Promise<{ offers: GpuOffer[]; live: boolean; error?: string }> {
  const key = process.env.PRIME_INTELLECT_API_KEY;
  if (!key) {
    return { offers: FALLBACK, live: false };
  }

  try {
    const url = new URL("https://api.primeintellect.ai/api/v1/availability/gpus");
    url.searchParams.set("page", "1");
    url.searchParams.set("page_size", "100");
    const res = await fetch(url.toString(), {
      headers: {
        Authorization: `Bearer ${key}`,
        Accept: "application/json",
      },
      next: { revalidate: 60 },
    });
    if (!res.ok) {
      const text = await res.text();
      return {
        offers: FALLBACK,
        live: false,
        error: `Prime availability ${res.status}: ${text.slice(0, 160)}`,
      };
    }
    const data = (await res.json()) as { items?: Record<string, unknown>[] };
    const items = Array.isArray(data.items) ? data.items : [];
    if (!items.length) return { offers: FALLBACK, live: false, error: "No live offers returned" };
    return {
      offers: items.map(mapLiveItem),
      live: true,
    };
  } catch (err) {
    return {
      offers: FALLBACK,
      live: false,
      error: err instanceof Error ? err.message : "Availability fetch failed",
    };
  }
}

function enrichOffers(
  offers: GpuOffer[],
  configured: boolean,
  subsidyUsd: number
): (GpuOffer & {
  offerType: string;
  integration: "integrated" | "external";
  tensoraPricePerHour: number;
})[] {
  const discountBps = subsidyUsd > 0 ? GPU_HOUSE_DISCOUNT_BPS : 0;
  return offers.map((offer) => {
    const p = String(offer.provider || "").toLowerCase();
    let offerType = "on-demand";
    if (p.includes("vast") || p.includes("tensordock")) offerType = "marketplace";
    else if (p.includes("coreweave") || offer.pricePerHour <= 0) offerType = "enterprise";

    const inStock =
      !String(offer.stockStatus).toLowerCase().includes("unavail") &&
      offer.pricePerHour > 0;
    const integration: "integrated" | "external" =
      configured && offer.source === "live" && inStock ? "integrated" : "external";

    const tensoraPricePerHour =
      Math.round(offer.pricePerHour * (1 - discountBps / 10000) * 1000) / 1000;

    return { ...offer, offerType, integration, tensoraPricePerHour };
  });
}

export async function GET() {
  const result = await fetchLiveOffers();
  const configured = Boolean(process.env.PRIME_INTELLECT_API_KEY);
  // Sandbox UI when Prime is missing (live or demo)
  const demoMode = isDemoMode() || !configured;
  const gpuSubsidyUsd = await getGpuSubsidyRemaining();

  return NextResponse.json({
    configured,
    live: Boolean(result.live && configured),
    demoMode,
    error: result.error || null,
    marketplace: "https://app.primeintellect.ai/dashboard/on-demand-gpus",
    offers: enrichOffers(result.offers, configured, gpuSubsidyUsd),
    total: result.offers.length,
    gpuSubsidyUsd,
    gpuDiscountBps: gpuSubsidyUsd > 0 ? GPU_HOUSE_DISCOUNT_BPS : 0,
    fetchedAt: new Date().toISOString(),
  });
}
