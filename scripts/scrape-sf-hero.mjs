// One-off: pull the sfcompute hero line-art, recolour to the Olora monochrome
// palette, namespace its ids, and emit an asset + an inline-able TS module.
// Usage: node scripts/scrape-sf-hero.mjs
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const html = await (await fetch("https://sfcompute.com/")).text();

const start = html.indexOf('<svg width="706"');
if (start < 0) throw new Error("hero svg not found");
// Walk to the matching </svg> (the hero may nest svgs).
let depth = 0;
let i = start;
let end = -1;
const re = /<svg\b|<\/svg>/g;
re.lastIndex = start;
for (let m; (m = re.exec(html)); ) {
  depth += m[0] === "</svg>" ? -1 : 1;
  if (depth === 0) {
    end = m.index + 6;
    break;
  }
  i = m.index;
}
if (end < 0) throw new Error("unterminated svg");
let svg = html.slice(start, end);

const vars = {
  "--color-dark-100": "#e2e2de",
  "--color-dark-200": "#cfcfcc",
  "--color-dark-300": "#b4b4b0",
  "--color-dark-500": "#a3a39e",
  "--color-dark-800": "#8a8a86",
  "--color-light-100": "#ffffff",
};
for (const [k, v] of Object.entries(vars)) svg = svg.replaceAll(`var(${k})`, v);
svg = svg.replace(/var\(--[a-z0-9-]+\)/gi, "#cfcfcc");

const hex = {
  "#4C78F5": "#3b69f3",
  "#3D64D8": "#3b69f3",
  "#4067D9": "#3b69f3",
  "#9DBAEE": "#cfcfcc",
  // Cool greys -> Olora warm greys.
  "#DFDFE2": "#e2e2de",
  "#C4C4C8": "#c9c9c4",
  "#C6C6C6": "#c9c9c4",
};
for (const [k, v] of Object.entries(hex)) svg = svg.replace(new RegExp(k, "gi"), v);
// Any leftover blue-ish rgb()/hex accents -> ink.
svg = svg.replace(/rgba?\(\s*(5\d|6\d|7\d)\s*,\s*(1\d\d)\s*,\s*2[0-5]\d[^)]*\)/g, "#3b69f3");

// Namespace ids and their references.
svg = svg.replace(/\b(hm|hd)-/g, "ol-");
// Strip inline visibility:hidden and fixed size so it scales.
svg = svg
  .replace(/\swidth="706"\s+height="298"/, "")
  .replace(/class="[^"]*"/, 'class="block h-auto w-full"')
  // Their Tailwind breakpoint class; we show the dials at every width.
  .replaceAll(' class="max-lg:invisible"', "");

mkdirSync(resolve(root, "public/lab-dashboard"), { recursive: true });
writeFileSync(resolve(root, "public/lab-dashboard/hero-line.svg"), svg);
writeFileSync(
  resolve(root, "src/components/olora/hero-line-art.ts"),
  `// Generated by scripts/scrape-sf-hero.mjs. Do not edit by hand.\n// Source artwork: sfcompute.com hero, recoloured monochrome.\nexport const HERO_LINE_SVG = ${JSON.stringify(svg)};\n`,
);
console.log("svg bytes", svg.length, "remaining blues", (svg.match(/#(4C78F5|3D64D8|9DBAEE)/gi) || []).length);
